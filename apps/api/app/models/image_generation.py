class ImageGenerationSize(str, Enum):
    """Reviewed dimensions supported by the selected GPT Image models."""

    SQUARE = "1024x1024"
    LANDSCAPE = "1536x1024"
    PORTRAIT = "1024x1536"


class ImageGenerationQuality(str, Enum):
    """Bounded quality choices with predictable operational cost."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ImageOutputFormat(str, Enum):
    """Image formats accepted from the provider boundary."""

    PNG = "png"
    JPEG = "jpeg"
    WEBP = "webp"


class ImageDataReferenceKind(str, Enum):
    """How generated data is made available to later storage code."""

    INLINE_BYTES = "inline_bytes"
    PROVIDER_URL = "provider_url"


class ImageGenerationErrorCategory(str, Enum):
    """Stable content-free failure categories for callers and operations."""

    CONFIGURATION = "configuration"
    SAFETY_DENIED = "safety_denied"
    RIGHTS_DENIED = "rights_denied"
    DUPLICATE_REQUEST = "duplicate_request"
    AUTHENTICATION = "authentication"
    RATE_LIMIT = "rate_limit"
    QUOTA = "quota"
    TIMEOUT = "timeout"
    UNAVAILABLE = "unavailable"
    MODERATION_BLOCKED = "moderation_blocked"
    REQUEST_REJECTED = "request_rejected"
    INVALID_RESPONSE = "invalid_response"


ASPECT_RATIO_SIZES = {
    ImageAspectRatio.SQUARE: ImageGenerationSize.SQUARE,
    ImageAspectRatio.LANDSCAPE: ImageGenerationSize.LANDSCAPE,
    ImageAspectRatio.PORTRAIT: ImageGenerationSize.PORTRAIT,
}


class OpenAIImageGenerationRequest(BaseModel):
    """Strict internal request containing every pre-provider decision."""

    request_id: UUID
    prompt: ImagePromptResult
    safety_result: ImageSafetyResult
    rights_decision: ArticleRightsDecision
    size: ImageGenerationSize | None = None
    quality: ImageGenerationQuality = ImageGenerationQuality.MEDIUM
    output_format: ImageOutputFormat = ImageOutputFormat.PNG
    safety_identifier: SecretStr | None = Field(default=None, max_length=128)

    @field_validator("safety_identifier")
    @classmethod
    def require_privacy_preserving_safety_identifier(
        cls,
        value: SecretStr | None,
    ) -> SecretStr | None:
        """Accept only the application's hashed, non-identifying identifier form."""

        if value is None:
            return None
        raw = value.get_secret_value()
        if len(raw) != 67 or not raw.startswith("nf_"):
            raise ValueError("Safety identifier must be an nf_ prefixed SHA-256 value.")
        try:
            int(raw[3:], 16)
        except ValueError as exc:
            raise ValueError(
                "Safety identifier must be an nf_ prefixed SHA-256 value."
            ) from exc
        return value

    @model_validator(mode="after")
    def require_size_matching_prompt_shape(self) -> "OpenAIImageGenerationRequest":
        expected = ASPECT_RATIO_SIZES[self.prompt.preferences.aspect_ratio]
        if self.size is not None and self.size != expected:
            raise ValueError("Image size must match the approved prompt aspect ratio.")
        return self

    @property
    def resolved_size(self) -> ImageGenerationSize:
        """Return the requested size or the controlled aspect-ratio mapping."""

        return self.size or ASPECT_RATIO_SIZES[self.prompt.preferences.aspect_ratio]

    model_config = ConfigDict(extra="forbid", frozen=True)


class ImageGenerationUsage(BaseModel):
    """Available provider usage without hard-coded price assumptions."""

    input_tokens: int | None = Field(default=None, ge=0)
    output_tokens: int | None = Field(default=None, ge=0)
    total_tokens: int | None = Field(default=None, ge=0)
    input_text_tokens: int | None = Field(default=None, ge=0)
    input_image_tokens: int | None = Field(default=None, ge=0)
    output_image_tokens: int | None = Field(default=None, ge=0)

    model_config = ConfigDict(frozen=True)


class GeneratedImageDataReference(BaseModel):
    """Masked generated bytes or a masked HTTPS provider retrieval reference."""

    kind: ImageDataReferenceKind
    media_type: Literal["image/png", "image/jpeg", "image/webp"]
    data: SecretBytes | None = Field(default=None, repr=False)
    retrieval_url: SecretStr | None = Field(default=None, repr=False)
    byte_length: int | None = Field(default=None, ge=1)
    sha256: str | None = Field(default=None, pattern=r"^[a-f0-9]{64}$")

    @model_validator(mode="after")
    def require_one_data_location(self) -> "GeneratedImageDataReference":
        if self.kind == ImageDataReferenceKind.INLINE_BYTES:
            if self.data is None or self.retrieval_url is not None:
                raise ValueError("Inline image data must contain bytes only.")
            if self.byte_length is None or self.sha256 is None:
                raise ValueError(
                    "Inline image data requires length and digest metadata."
                )
        elif self.retrieval_url is None or self.data is not None:
            raise ValueError("Provider URL image data must contain a URL only.")
        return self

    model_config = ConfigDict(extra="forbid", frozen=True)


class OpenAIImageGenerationResult(BaseModel):
    """Consistent internal result returned without exposing credentials."""

    request_id: UUID
    provider: Literal["openai"] = "openai"
    model_identifier: str = Field(min_length=1, max_length=200)
    status: Literal["completed"] = "completed"
    image_data_reference: GeneratedImageDataReference
    usage_metadata: ImageGenerationUsage
    provider_request_id: str | None = Field(default=None, max_length=200)
    prompt_version: str = Field(pattern=r"^image_prompt_v[1-9][0-9]*$")
    safety_policy_version: str = Field(pattern=r"^image_safety_v[1-9][0-9]*$")
    safety_evaluation_id: UUID
    rights_version_id: UUID
    size: ImageGenerationSize
    quality: ImageGenerationQuality
    output_format: ImageOutputFormat
    created_at: datetime
    ai_generated_designation: Literal["AI-generated illustration"] = (
        "AI-generated illustration"
    )
    human_review_required: Literal[True] = True
    error_category: None = None

    model_config = ConfigDict(extra="forbid", frozen=True)


